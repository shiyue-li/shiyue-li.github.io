"""Write the CV's talks and papers sections from the website's data files.

    python3 cv/generate.py

reads data/talks.yaml and data/papers.yaml and writes cv/sections/talks.tex
and cv/sections/papers.tex, so a talk or paper is added in one place and
shows up on both the website and the CV. Needs PyYAML.
"""
import re
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
SECTIONS = REPO / "cv" / "sections"

# The website uses the names people go by; the CV uses their full names.
FULL_NAMES = {"Chris Eur": "Christopher Eur", "Nick Proudfoot": "Nicholas Proudfoot"}


def tex(text):
    """Escape plain text for LaTeX, keeping $...$ math and setting Chinese in \\han{}."""
    out = []
    for part in re.split(r"(\$[^$]*\$)", text):
        if part.startswith("$"):
            out.append(part)
            continue
        part = part.replace("\\", r"\textbackslash{}")
        for char in "&%#_":
            part = part.replace(char, "\\" + char)
        part = part.replace("--", r"\textendash{}").replace("–", r"\textendash{}")
        part = re.sub(r"([\u3400-\u9fff]+)", r"\\han{\1}", part)
        out.append(part)
    return "".join(out)


def url(link):
    return (link or "").replace("%", r"\%").replace("#", r"\#")


def and_list(names):
    if len(names) > 2:
        return ", ".join(names[:-1]) + ", and " + names[-1]
    return " and ".join(names)


def talks():
    lines = ["\\cvsection{Invited Talks}", ""]
    for t in yaml.safe_load((REPO / "data" / "talks.yaml").read_text()):
        lines.append(
            f"\\talk{{{t['date']}}}{{{tex(t['venue'])}}}"
            f"{{{tex(t.get('event', ''))}}}{{{url(t.get('url'))}}}"
        )
    return "\n".join(lines) + "\n"


def papers():
    entries = yaml.safe_load((REPO / "data" / "papers.yaml").read_text())
    lines = ["\\cvsection{Preprints and Publications}", ""]
    for i, p in enumerate(entries):
        coauthors = and_list([FULL_NAMES.get(c["name"], c["name"]) for c in p.get("coauthors") or []])
        if p.get("venue"):
            where, where_url = tex(p["venue"]), url(p.get("venue_url"))
        else:
            arxiv_id = p["url"].rstrip("/").rsplit("/", 1)[-1]
            where, where_url = f"arXiv:{arxiv_id}", url(p["url"])
        lines.append(
            f"\\paper{{{len(entries) - i}}}{{{tex(p['title'])}}}{{{url(p['url'])}}}"
            f"{{{tex(coauthors)}}}{{{where}}}{{{where_url}}}"
        )
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    header = "% Generated by cv/generate.py from data/*.yaml; edit those files instead.\n"
    (SECTIONS / "talks.tex").write_text(header + talks())
    (SECTIONS / "papers.tex").write_text(header + papers())
